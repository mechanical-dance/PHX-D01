"""Generate build/lxr1_map.h: translate LXR-2 kit bytes to the LXR-1 (0.37 / LXR02Open) engine, by parameter name.

usage: gen_map.py LXR2_TREE LXR1_TREE OUT.h
"""
import re, sys
from pathlib import Path


def enum(path):
    src = Path(path).read_text(errors="replace")
    body = src[src.index("PAR_NONE"):]
    names, v = {}, 0
    for m in re.finditer(r"^\s*(PAR_\w+|END_OF_SOUND_PARAMETERS)\s*(?:=\s*(\w+))?\s*,", "\t" + body, re.M):
        n, eq = m.groups()
        if eq:
            v = names[eq] if eq in names else int(eq, 0)
        names[n] = v
        v += 1
        if n == "END_OF_SOUND_PARAMETERS":
            break
    return names


def modtargets(path):
    src = Path(path).read_text(errors="replace")
    block = src[src.index("modTargets[]"):]
    block = block[:block.index("};")]
    block = re.sub(r"//[^\n]*|/\*.*?\*/", "", block, flags=re.S)
    return re.findall(r"\{\s*TEXT_\w+\s*,\s*(PAR_\w+)\s*\}", block)


lxr2, lxr1, out = sys.argv[1:4]
p2 = enum(f"{lxr2}/Core/Inc/Parameters.h")
p1 = enum(f"{lxr1}/Core/Preset/ParameterArray.h")
mt2 = modtargets(f"{lxr2}/Core/Src/menu/Cc2Text.c")
n2, n1 = p2["END_OF_SOUND_PARAMETERS"], p1["END_OF_SOUND_PARAMETERS"]
by_index2 = {}
for name, v in p2.items():
    if v < n2:
        by_index2.setdefault(v, name)   # first name wins (aliases like PAR_OSC_WAVE_DRUM1 = PAR_MOD_WHEEL)
param_map = [p1.get(by_index2.get(i, ""), -1) for i in range(n2)]
param_map = [x if 0 <= x < n1 else -1 for x in param_map]
mt_map = [p1.get(name, 0) if p1.get(name, n1) < n1 else 0 for name in mt2]

with open(out, "w") as f:
    f.write(f"/* Generated by gen_map.py from {lxr2} and {lxr1}. Do not edit. */\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define LXR2_NUM_PARAMS {n2}\n#define LXR1_NUM_PARAMS {n1}\n#define LXR2_NUM_MODTARGETS {len(mt2)}\n")
    f.write("/* LXR-2 kit byte index -> LXR-1 parameter index, -1 if the LXR-1 has no such parameter */\n")
    f.write("static const int16_t lxr2_to_lxr1_param[LXR2_NUM_PARAMS] = {" + ",".join(map(str, param_map)) + "};\n")
    f.write("/* LXR-2 modTargets index -> LXR-1 parameter number (0 = none) */\n")
    f.write("static const uint8_t lxr2_modtarget_to_lxr1_param[LXR2_NUM_MODTARGETS] = {" + ",".join(map(str, mt_map)) + "};\n")
missing = [by_index2.get(i, "?") for i, x in enumerate(param_map) if x < 0]
print(f"{out}: {n2 - len(missing)}/{n2} params mapped, {len(mt2)} mod targets; LXR-2 only: {', '.join(missing)}")
