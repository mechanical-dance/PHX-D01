#!/bin/sh
# Regenerates app/web/pages.js from the LXR-2 firmware's menu tables. Usage: tools/gen_pages.sh [path/to/lxr-desktop-app]
set -e
C=${1:-$HOME/code/vendor/lxr-02/lxr-desktop-app}/Core
T=$(mktemp -d)
awk 'NR>=258 && /^};/ {print; exit} NR>=258' "$C/Src/menu/menu.c" | sed 's/PROGMEM//' > "$T/dtypes.inc"
awk 'NR>=95 && /^};/ {print; exit} NR>=95' "$C/Src/menu/menu.c" | sed 's/PROGMEM//' > "$T/names.inc"
cc -w -Ishim -I"$T" -I"$C/Inc" -I"$C/Inc/menu" -I"$C/Inc/Soundengine" -I"$C/Inc/Preset" tools/gen_pages.c -o "$T/gen"
{ echo '// Generated by tools/gen_pages.sh from the LXR-2 firmware menu tables. Do not edit.'
  printf 'const LXR_PAGES = '; "$T/gen"; echo ';'; } > app/web/pages.js
rm -rf "$T"
