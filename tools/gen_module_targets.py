#!/usr/bin/env python3
"""Extracts the LXR-Drum module's mod-matrix target table from its firmware image (closed source, so the table is
found by shape) and writes host/module_targets.h and app/web/modtargets.js.

The table is the desktop's modTargets (Cc2Text.c: {name index, param} pairs, 4 bytes each) with, per voice, a "v/o"
entry first (name 113, param PAR_UNUSED_n) and a morph entry last (name 40, the module's PAR_MORPH = 302).
A kit's mod slot stores an index into this table. Usage: tools/gen_module_targets.py path/to/LXRE_V2_*.img
"""
import struct
import sys
from pathlib import Path

PAR_COARSE1, PAR_FINE1, PAR_OSC_WAVE_DRUM1, PAR_PWM_1 = 8, 9, 1, 228   # Parameters.h (desktop and module agree < 247)
NAME_VO, MODULE_PAR_MORPH = 113, 302

img = Path(sys.argv[1]).read_bytes()[16:]   # skip the LXRERIMG header
sig = b"".join(struct.pack("<BxH", n, p) for n, p in ((1, PAR_COARSE1), (2, PAR_FINE1), (33, PAR_OSC_WAVE_DRUM1), (85, PAR_PWM_1)))
at = img.find(sig)
assert at > 12 and img.find(sig, at + 1) < 0, "target table not found (or found twice)"
start = at - 12   # off, global sample rate, drum1 v/o
entries = []
for o in range(start, len(img), 4):
    n, p = img[o], struct.unpack_from("<H", img, o + 2)[0]
    if p > MODULE_PAR_MORPH or (entries and n == 0 and p == 0): break
    entries.append((n, p))
assert entries[0] == (0, 0) and entries[2][0] == NAME_VO and len(entries) == 241, (entries[:3], len(entries))

root = Path(__file__).resolve().parent.parent
params = ", ".join(str(p) for _, p in entries)
(root / "host/module_targets.h").write_text(
    "/* Generated by tools/gen_module_targets.py from the LXR-Drum firmware image. Do not edit.\n"
    "   The module's mod-matrix targets: param number per target index (0 = off; v/o = PAR_UNUSED_n; 302 = morph). */\n"
    f"#define MODULE_TARGETS {len(entries)}\n"
    f"static const uint16_t module_target_param[MODULE_TARGETS] = {{{params}}};\n")
pairs = ",".join(f"[{n},{p}]" for n, p in entries)
(root / "app/web/modtargets.js").write_text(
    "// Generated by tools/gen_module_targets.py from the LXR-Drum firmware image. Do not edit.\n"
    "// The module's mod-matrix targets as [name index (LXR_PAGES.names; 113 = v/o), param]; a slot stores the index.\n"
    f"const MODULE_TARGETS = [{pairs}];\n")
print(f"{len(entries)} targets at image offset {start:#x}")
